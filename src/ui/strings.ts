export type StringKey = keyof (typeof catalogs)["en"];

export function stringKeys(): StringKey[] {
  return Object.keys(catalogs.en) as StringKey[];
}

export function text(locale: Locale, key: StringKey, vars?: Record<string, string>): string {
  const template: string = catalogs[locale][key];
  if (!vars) {
    return template;
  }
  return template.replace(/\{(\w+)\}/g, (match, name: string) => vars[name] ?? match);
}
